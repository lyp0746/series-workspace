n_box = n_wrap = 0
for i in range(1, 26):
    f = "ch%02d.html" % i
    s = io.open(f, encoding="utf-8").read()
    # 1) 把“读法：”段落框化
    def wrap(m):
        global n_wrap
        n_wrap += 1
        return '<div class="box"><p>%s</p></div>' % m.group(1)
    s = re.sub(r'<p>(<strong>读法：</strong>.*?)</p>', wrap, s, flags=re.S)
    # 2) 插入“给专家的注”
    key = "ch%02d" % i
    if key in EXPERT:
        box = ('\n<div class="box box-expert"><p><strong>【给专家的注】</strong>%s</p></div>\n' % EXPERT[key])
        a = re.search(r'<h3 id="sec\d+-ref">\d+　本章参考文献</h3>', s)
        if a:
            s = s[:a.start()] + box + s[a.start():]
            n_box += 1
    io.open(f, "w", encoding="utf-8").write(s)
print("读法框化", n_wrap, "处；给专家的注", n_box, "个")
