FIELDS = ["id", "domain", "q1a", "q1b", "swap", "swapnote", "q2", "q3",
          "q3core", "q4", "presence", "gaveup", "basis", "grade", "refs"]


def rows():
    out = []
    for c in DOMAINS:
        r = dict(zip(FIELDS, c))
        r["q2l"] = [x for x in r["q2"].split(",") if x]
        out.append(r)
    return out


def stats():
    import collections
    rs = rows()
    acts = {a: sum(1 for r in rs if a in r["q2l"]) for a in ACTIONS}
    pre = collections.Counter(r["presence"] for r in rs)
    cross = {(w, p): sum(1 for r in rs if r["q3"] == w and r["presence"] == p)
             for w in "ABC" for p in PRESENCE}
    return dict(
        n=len(rs),
        q1a=collections.Counter(r["q1a"] for r in rs),
        q1b=collections.Counter(r["q1b"] for r in rs),
        actions=acts,
        q3=collections.Counter(r["q3"] for r in rs),
        q4=collections.Counter(r["q4"] for r in rs),
        presence=pre,
        cross=cross,
        swaps=sum(1 for r in rs if r["swap"] == "Y"),
        swap_ids=[r["id"] for r in rs if r["swap"] == "Y"],
        basis=collections.Counter(r["basis"] for r in rs),
        grade=collections.Counter(r["grade"] for r in rs),
    )


