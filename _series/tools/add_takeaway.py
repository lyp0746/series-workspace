BOX = '<div class="box box-takeaway"><p><b>一句话带走：</b>{}</p></div>\n'


def main():
    total = 0
    for book, table in TAKE.items():
        src = os.path.join(ROOT, book, "source")
        hit = 0
        for no, line in table.items():
            p = os.path.join(src, f"ch{no:02d}.html")
            if not os.path.exists(p):
                print(f"  ! {book} 缺 {os.path.basename(p)}")
                continue
            t = io.open(p, encoding="utf-8").read()
            if "一句话带走" in t:
                continue
            m = re.search(r"<h3[^>]*>\s*本章参考文献", t)
            if m:
                t = t[:m.start()] + BOX.format(line) + "\n" + t[m.start():]
            elif "</body>" in t:
                t = t.replace("</body>", BOX.format(line) + "</body>", 1)
            elif "本章参考文献" in t:
                t = t.replace("本章参考文献", BOX.format(line) + "\n本章参考文献", 1)
            else:
                t = t.rstrip() + "\n" + BOX.format(line)
            io.open(p, "w", encoding="utf-8").write(t)
            hit += 1
        print(f"{book:26} 写入 {hit}/{len(table)}")
        total += hit
    print("合计", total)


if __name__ == "__main__":
    sys.exit(main())
