for book, plan in PLAN.items():
    pj = os.path.join(ROOT, book, "source", "parts.json")
    parts = json.load(io.open(pj, encoding="utf-8"))
    idx = {}
    for p in parts:
        for c in p.get("chapters", []):
            idx[str(c["no"])] = c
    out = []
    for title, nos, desc in plan:
        chs = []
        for n in nos:
            if n not in idx:
                print(f"  ! {book} 缺第 {n} 章")
                continue
            chs.append(idx[n])
        out.append({"part": title, "desc": desc, "chapters": chs})
    json.dump(out, io.open(pj, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"{book:24} {'/'.join(str(len(p['chapters'])) for p in out)}")
