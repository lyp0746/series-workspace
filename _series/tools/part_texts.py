def apply(book, table):
    import json, os
    pj = os.path.join(ROOT, book, "source", "parts.json")
    parts = json.load(open(pj, encoding="utf-8"))
    if len(parts) != len(table):
        print(book, "parts", len(parts), "table", len(table), "skip")
        return
    for p, (intro, summary) in zip(parts, table):
        p["intro"], p["summary"] = intro, summary
    json.dump(parts, open(pj, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(book, "ok", len(parts))


