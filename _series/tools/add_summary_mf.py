def main():
    hit = 0
    for no, items in S.items():
        p = os.path.join(BOOK, f"ch{no:02d}.html")
        if not os.path.exists(p):
            print("缺", p)
            continue
        t = io.open(p, encoding="utf-8").read()
        if "本章小结" in t:
            continue
        li = "".join(f"<li>{x}</li>" for x in items)
        box = f'<div class="box box-summary"><span class="bt">本章小结</span>\n<ul>{li}</ul></div>\n\n'
        m = re.search(r'<div class="box box-takeaway">', t)
        if m:
            t = t[:m.start()] + box + t[m.start():]
        elif "<h3[^>]*>本章参考文献" in t:
            m = re.search(r"<h3[^>]*>本章参考文献", t)
            t = t[:m.start()] + box + t[m.start():]
        else:
            t = t.rstrip() + "\n" + box
        io.open(p, "w", encoding="utf-8").write(t)
        hit += 1
    print("mind-forks 本章小结写入", hit)
    return 0


if __name__ == "__main__":
    sys.exit(main())
