def main():
    REL.mkdir(parents=True, exist_ok=True)
    if ASSETS.exists(): shutil.rmtree(ASSETS)
    ASSETS.mkdir(parents=True)
    parts = [FRONT]
    for i, book in enumerate(BOOKS, 1):
        md_path = BASE/book/"output"/"markdown"/"book.md"
        if not md_path.exists():
            print("缺:", md_path); continue
        txt = md_path.read_text(encoding="utf-8")
        src_assets = md_path.parent/"assets"
        if src_assets.exists():
            dst = ASSETS/book; dst.mkdir(parents=True, exist_ok=True)
            for f in src_assets.rglob("*"):
                if f.is_file():
                    target = dst / f.relative_to(src_assets)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(f, target)
        txt = txt.replace("](assets/", f"](assets/{book}/")
        vol, title = TITLES[book]
        parts.append(f"\n\n---\n\n## {vol}　{title}\n\n{txt.strip()}\n")
    parts.append("\n\n---\n\n# 第二部　十四篇工作论文\n")
    for repo, mdfile, head in PAPERS:
        md_path = BASE/repo/mdfile
        txt = md_path.read_text(encoding="utf-8")
        dst = ASSETS/repo; dst.mkdir(parents=True, exist_ok=True)
        for m in re.findall(r"!\[[^\]]*\]\(([^)]+)\)", txt):
            if m.startswith(("http", "data:")): continue
            src = BASE/repo/m
            if src.exists() and src.is_file():
                shutil.copy2(src, dst/src.name)
        txt = re.sub(r"\]\((fig[^)]+)\)", lambda mm: f"](assets/{repo}/{mm.group(1)})", txt)
        parts.append(f"\n\n---\n\n## {head}\n\n{txt.strip()}\n")
    parts.append(AFTER)
    out = REL/"03-合集.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print("wrote", out, round(out.stat().st_size/1e6,1), "MB | assets:", sum(1 for _ in ASSETS.rglob("*") if _.is_file()))

if __name__ == "__main__":
    main()
