    s["bneck"] = Counter(t["bneck"] for t in TERMS)
    s["swap"] = Counter(t["swap"] for t in TERMS)
    s["vertex"] = Counter(t["cat"] for t in TERMS)
    s["impl"] = Counter(t["impl_g"] for t in TERMS)
    s["grade"] = Counter(t["grade"] for t in TERMS)
    s["cgrade"] = Counter(t["cgrade"] for t in TERMS)
