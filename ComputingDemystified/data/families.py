def audit():
    names = {t["term"] for t in TERMS}
    fam_terms = [t for _, _, _, ts in FAMILIES for t in ts]
    missing_terms = [t for t in fam_terms if t not in names]
    uncovered = [(l, f) for l, f, _, ts in FAMILIES if not ts]
    orphans = [t["term"] for t in TERMS if t["term"] not in fam_terms]
    dup = [t for t in set(fam_terms) if fam_terms.count(t) > 1]
    return dict(missing_terms=missing_terms, uncovered=uncovered,
                orphans=orphans, dup=dup,
                n_families=len(FAMILIES), n_terms=len(TERMS))


if __name__ == "__main__":
    a = audit()
    print("families:", a["n_families"], " terms:", a["n_terms"])
    print("missing terms:", a["missing_terms"])
    print("uncovered families:", a["uncovered"])
    print("orphan terms:", a["orphans"])
    print("duplicated:", a["dup"])
    from collections import Counter
    print(Counter(l for l, _, _, _ in FAMILIES))
