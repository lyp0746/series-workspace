"""第二遍：把残留的旧统计口径换掉（五处→七处、四项计数、证伪率）。"""
import pathlib
import re

P = pathlib.Path(__file__).resolve().parent.parent / "source" / "paper.md"
t = P.read_text(encoding="utf-8")
subs = [
    ("（40／19／3、17.7%）", "（76／27／7、14.5%）"),
    ("「17.7% 是打自己」", "「14.5% 是打自己」"),
    ("| 17.7% 打自己 |", "| 14.5% 打自己 |"),
    ("40 条已核销、19 条未核销、3 条撤回、11 条（17.7%）", "76 条已核销、27 条未核销、7 条撤回、16 条（14.5%）"),
    ("证伪 6 ＋ 撤回 3 = 9/48 = 18.8%", "证伪 9 ＋ 撤回 7 = 16/110 = 14.5%"),
    ("20／17／11／0／0", "77／18／14／0／1"),
    ("110 条 31／14／3／18.8%；A2、B25、C21", "110 条 76／27／7／14.5%；A3、B55、C52"),
    ("14 条未核销、3 条撤回、2 条 A", "27 条未核销、7 条撤回、3 条 A"),
    ("18.8%", "14.5%"),
    ("五处", "七处"),
]
n = 0
for a, b in subs:
    c = t.count(a)
    t = t.replace(a, b)
    n += c
    print("%-40s x%d" % (a[:36], c))
P.write_text(t, encoding="utf-8")
left = [p for p in ("17.7", "18.8", "五处", "62", "九篇") if p in t]
print("残留:", left)
